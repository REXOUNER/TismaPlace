const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('arcade', {
  getGames: () => ipcRenderer.invoke('library:get'),
  onLibraryUpdated: callback => { const listener = (_event, payload) => callback(payload); ipcRenderer.on('library:updated', listener); return () => ipcRenderer.removeListener('library:updated', listener); },
  onLibraryUpdateError: callback => { const listener = (_event, payload) => callback(payload); ipcRenderer.on('library:update-error', listener); return () => ipcRenderer.removeListener('library:update-error', listener); },
  setFullscreen: enabled => ipcRenderer.invoke('window:fullscreen', enabled),
  getAppVersion: () => ipcRenderer.invoke('app:version'),
  checkForUpdates: () => ipcRenderer.invoke('updates:check'),
  downloadUpdate: () => ipcRenderer.invoke('updates:download'),
  installUpdate: () => ipcRenderer.invoke('updates:install'),
  onUpdateStatus: callback => { const listener = (_event, state) => callback(state); ipcRenderer.on('updates:status', listener); return () => ipcRenderer.removeListener('updates:status', listener); },
  mediaCommand: command => ipcRenderer.invoke('media:command', command),
  getMediaState: () => ipcRenderer.invoke('media:get-state'),
  onMediaState: callback => { const listener = (_event, state) => callback(state); ipcRenderer.on('media:state', listener); return () => ipcRenderer.removeListener('media:state', listener); },
  getSystemVolume: () => ipcRenderer.invoke('media:volume-get'),
  onSystemVolume: callback => { const listener = (_event, state) => callback(state); ipcRenderer.on('media:volume-state', listener); return () => ipcRenderer.removeListener('media:volume-state', listener); },
  setSystemVolume: level => ipcRenderer.invoke('media:volume-set', level),
  toggleSystemMute: () => ipcRenderer.invoke('media:volume-mute'),
  chooseWallpaper: () => ipcRenderer.invoke('wallpaper:choose'),
  clearWallpaper: wallpaperUrl => ipcRenderer.invoke('wallpaper:clear', wallpaperUrl),
  exportBackup: preferences => ipcRenderer.invoke('backup:export', preferences),
  importBackup: () => ipcRenderer.invoke('backup:import'),
  restoreAutoBackup: () => ipcRenderer.invoke('backup:restore-auto'),
  getCollections: () => ipcRenderer.invoke('collections:get'),
  setCollectionsOrder: names => ipcRenderer.invoke('collections:set-order', names),
  addCollection: name => ipcRenderer.invoke('collection:add', name),
  renameCollection: (oldName, newName) => ipcRenderer.invoke('collection:rename', oldName, newName),
  getCollectionCovers: () => ipcRenderer.invoke('collection:cover:get'),
  chooseCollectionCover: name => ipcRenderer.invoke('collection:cover:choose', name),
  clearCollectionCover: name => ipcRenderer.invoke('collection:cover:clear', name),
  removeCollection: name => ipcRenderer.invoke('collection:remove', name),
  setGameCollection: (id, name) => ipcRenderer.invoke('game:set-collection', id, name),
  setCollectionOrder: (name, ids) => ipcRenderer.invoke('game:set-collection-order', name, ids),
  setGameGenre: (id, genre) => ipcRenderer.invoke('game:set-genre', id, genre),
  setGameTags: (id, tags) => ipcRenderer.invoke('game:set-tags', id, tags),
  setGameStatus: (id, status) => ipcRenderer.invoke('game:set-status', id, status),
  setGameNotes: (id, notes) => ipcRenderer.invoke('game:set-notes', id, notes),
  setGameLaunchProfile: (id, profile) => ipcRenderer.invoke('game:set-launch-profile', id, profile),
  openScreenshots: id => ipcRenderer.invoke('game:screenshots', id),
  getSteamCredentials: () => ipcRenderer.invoke('steam:credentials:get'),
  saveSteamCredentials: (steamId, apiKey) => ipcRenderer.invoke('steam:credentials:save', steamId, apiKey),
  clearSteamCredentials: () => ipcRenderer.invoke('steam:credentials:clear'),
  syncSteamPlaytime: () => ipcRenderer.invoke('steam:playtime:sync'),
  addGame: game => ipcRenderer.invoke('game:add', game),
  removeGame: id => ipcRenderer.invoke('game:remove', id),
  setGamesCollection: (ids, name) => ipcRenderer.invoke('games:bulk-set-collection', ids, name),
  updateGames: (ids, action, value) => ipcRenderer.invoke('games:bulk-update', ids, action, value),
  removeGames: ids => ipcRenderer.invoke('games:bulk-remove', ids),
  toggleFavorite: id => ipcRenderer.invoke('game:toggle-favorite', id),
  chooseCover: id => ipcRenderer.invoke('game:choose-cover', id),
  fetchCovers: force => ipcRenderer.invoke('games:fetch-covers', force),
  chooseGame: () => ipcRenderer.invoke('game:choose'),
  chooseCompanion: () => ipcRenderer.invoke('game:choose-companion'),
  repairGame: id => ipcRenderer.invoke('game:repair', id),
  launchGame: id => ipcRenderer.invoke('game:launch', id),
  scanGames: () => ipcRenderer.invoke('games:scan')
});

